// Generates src/api/schema.gen.ts from src/api/openapi.json, which
// scripts/export_openapi.py (repo root) exports from the FastAPI app.
//
// Hand-rolled on purpose: openapi-typescript and @hey-api/openapi-ts drive the
// TypeScript 5 compiler API, which the Go-native TypeScript 7 no longer ships.
// The backend uses a small subset of JSON Schema, so this covers that subset
// and fails loudly on anything else instead of guessing.
//
//   node scripts/gen-api-types.mjs           write the file
//   node scripts/gen-api-types.mjs --check   exit 1 when it is out of date

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const INPUT = resolve(here, '../src/api/openapi.json')
const OUTPUT = resolve(here, '../src/api/schema.gen.ts')
const SCHEMA_REF = '#/components/schemas/'

const UNSUPPORTED = [
  'prefixItems',
  'not',
  'if',
  'then',
  'else',
  'patternProperties',
  'propertyNames',
  'dependentSchemas',
  'unevaluatedProperties',
  '$defs',
]

const HEADER = `// GENERATED by scripts/gen-api-types.mjs from openapi.json. Do not edit.
//
// Regenerate after any change to the backend's schemas:
//   python scripts/export_openapi.py   (repo root)
//   npm run gen:api                    (frontend/)
//
// Every property of a schema reachable from a response is required: FastAPI
// serialises every field, while Pydantic leaves a defaulted one out of the
// spec's "required". A schema shared with a request follows the same rule;
// request-only schemas keep the spec's optionality.
`

function typeName(name) {
  const clean = name.replace(/[^A-Za-z0-9_$]/g, '')
  if (!clean || /^\d/.test(clean)) throw new Error(`Cannot name schema "${name}"`)
  return clean
}

function refName(ref) {
  if (!ref.startsWith(SCHEMA_REF)) throw new Error(`Unsupported $ref "${ref}"`)
  return typeName(ref.slice(SCHEMA_REF.length))
}

function literal(value) {
  if (typeof value === 'string') {
    return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
  }
  if (value === null || typeof value === 'number' || typeof value === 'boolean') {
    return String(value)
  }
  throw new Error(`Unsupported literal ${JSON.stringify(value)}`)
}

function propertyKey(key) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : literal(key)
}

// Splits a rendered type on a separator that sits outside any brackets or
// string literal, so `Record<string, number | null> | null` yields two parts.
function splitTopLevel(type, separator) {
  const parts = []
  let depth = 0
  let quoted = false
  let start = 0
  for (let i = 0; i < type.length; i++) {
    const c = type[i]
    if (quoted) {
      if (c === '\\') i++
      else if (c === "'") quoted = false
    } else if (c === "'") {
      quoted = true
    } else if ('<{(['.includes(c)) {
      depth++
    } else if ('>})]'.includes(c)) {
      depth--
    } else if (depth === 0 && c === separator) {
      parts.push(type.slice(start, i).trim())
      start = i + 1
    }
  }
  parts.push(type.slice(start).trim())
  return parts
}

function isCompound(type) {
  return splitTopLevel(type, '|').length > 1 || splitTopLevel(type, '&').length > 1
}

function union(members) {
  const unique = [...new Set(members.flatMap((m) => splitTopLevel(m, '|')))]
  if (unique.includes('unknown')) return 'unknown'
  return [...unique.filter((m) => m !== 'null'), ...unique.filter((m) => m === 'null')].join(
    ' | ',
  )
}

function render(schema, ctx, indent) {
  if (schema === true) return 'unknown'
  if (schema === false) return 'never'
  if (typeof schema !== 'object' || schema === null) {
    throw new Error(`Invalid schema ${JSON.stringify(schema)}`)
  }
  for (const key of UNSUPPORTED) {
    if (key in schema) throw new Error(`Unsupported keyword "${key}"`)
  }
  if ('$ref' in schema) return refName(schema.$ref)
  if ('const' in schema) return literal(schema.const)
  if ('enum' in schema) return union(schema.enum.map(literal))
  if ('anyOf' in schema || 'oneOf' in schema) {
    return union((schema.anyOf ?? schema.oneOf).map((s) => render(s, ctx, indent)))
  }
  if ('allOf' in schema) {
    return schema.allOf
      .map((s) => render(s, ctx, indent))
      .map((t) => (isCompound(t) ? `(${t})` : t))
      .join(' & ')
  }
  const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : []
  if (types.length === 0) {
    const objectLike = 'properties' in schema || 'additionalProperties' in schema
    return objectLike ? renderObject(schema, ctx, indent) : 'unknown'
  }
  return union(types.map((t) => renderType(t, schema, ctx, indent)))
}

function renderType(type, schema, ctx, indent) {
  switch (type) {
    case 'string':
      return schema.format === 'binary' || 'contentMediaType' in schema ? 'Blob' : 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array': {
      const item = schema.items === undefined ? 'unknown' : render(schema.items, ctx, indent)
      return isCompound(item) ? `(${item})[]` : `${item}[]`
    }
    case 'object':
      return renderObject(schema, ctx, indent)
    default:
      throw new Error(`Unsupported type "${type}"`)
  }
}

function objectBody(schema, ctx, indent) {
  const required = new Set(schema.required ?? [])
  const pad = '  '.repeat(indent + 1)
  const lines = Object.keys(schema.properties ?? {})
    .sort()
    .map((key) => {
      const optional = ctx.allRequired || required.has(key) ? '' : '?'
      return `${pad}${propertyKey(key)}${optional}: ${render(schema.properties[key], ctx, indent + 1)}`
    })
  const extra = schema.additionalProperties
  if (extra !== undefined && extra !== false) {
    if (extra !== true && Object.keys(extra).length > 0) {
      throw new Error('Typed additionalProperties alongside properties is not supported')
    }
    lines.push(`${pad}[key: string]: unknown`)
  }
  return `{\n${lines.join('\n')}\n${'  '.repeat(indent)}}`
}

function renderObject(schema, ctx, indent) {
  if (Object.keys(schema.properties ?? {}).length > 0) return objectBody(schema, ctx, indent)
  const extra = schema.additionalProperties
  if (extra === false) return 'Record<string, never>'
  const value = extra === undefined || extra === true ? 'unknown' : render(extra, ctx, indent)
  return `Record<string, ${value}>`
}

function collectRefs(node, into) {
  if (Array.isArray(node)) {
    for (const item of node) collectRefs(item, into)
  } else if (node && typeof node === 'object') {
    for (const [key, value] of Object.entries(node)) {
      if (key === '$ref' && typeof value === 'string') into.add(value)
      else collectRefs(value, into)
    }
  }
}

function responseReachable(spec) {
  const schemas = spec.components?.schemas ?? {}
  const roots = new Set()
  for (const operations of Object.values(spec.paths ?? {})) {
    for (const operation of Object.values(operations)) {
      for (const response of Object.values(operation?.responses ?? {})) {
        for (const media of Object.values(response?.content ?? {})) {
          collectRefs(media.schema, roots)
        }
      }
    }
  }
  const reachable = new Set()
  const queue = [...roots]
  while (queue.length > 0) {
    const ref = queue.pop()
    if (!ref.startsWith(SCHEMA_REF)) throw new Error(`Unsupported $ref "${ref}"`)
    const name = ref.slice(SCHEMA_REF.length)
    if (reachable.has(name)) continue
    reachable.add(name)
    const nested = new Set()
    collectRefs(schemas[name], nested)
    queue.push(...nested)
  }
  return reachable
}

function isInterface(schema) {
  const structural = ['$ref', 'const', 'enum', 'anyOf', 'oneOf', 'allOf']
  return (
    Object.keys(schema.properties ?? {}).length > 0 &&
    (schema.type === undefined || schema.type === 'object') &&
    !structural.some((k) => k in schema)
  )
}

function generate(spec) {
  const schemas = spec.components?.schemas ?? {}
  const reachable = responseReachable(spec)
  const seen = new Map()
  const blocks = Object.keys(schemas)
    .map((name) => [typeName(name), name])
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([identifier, name]) => {
      if (seen.has(identifier)) {
        throw new Error(`Schemas "${seen.get(identifier)}" and "${name}" share a type name`)
      }
      seen.set(identifier, name)
      const schema = schemas[name]
      const ctx = { allRequired: reachable.has(name) }
      try {
        return isInterface(schema)
          ? `export interface ${identifier} ${objectBody(schema, ctx, 0)}`
          : `export type ${identifier} = ${render(schema, ctx, 0)}`
      } catch (error) {
        throw new Error(`${name}: ${error.message}`, { cause: error })
      }
    })
  return `${HEADER}\n${blocks.join('\n\n')}\n`
}

function readIfExists(path) {
  try {
    return readFileSync(path, 'utf8').replace(/\r\n/g, '\n')
  } catch {
    return null
  }
}

const output = generate(JSON.parse(readFileSync(INPUT, 'utf8')))
if (process.argv.includes('--check')) {
  if (readIfExists(OUTPUT) !== output) {
    console.error(
      'src/api/schema.gen.ts is out of date: run `npm run gen:api` in frontend/ and commit it.',
    )
    process.exit(1)
  }
} else {
  writeFileSync(OUTPUT, output, 'utf8')
}
